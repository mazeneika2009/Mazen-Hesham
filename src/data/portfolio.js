// Map a `projects` row onto the release-shaped card the deck/detail UI expects.
export function projectToCard(p) {
  let gallery = [];
  if (p.gallery_json) {
    try {
      const g = JSON.parse(p.gallery_json);
      if (Array.isArray(g)) gallery = g.filter((u) => typeof u === 'string');
    } catch {
      gallery = [];
    }
  }
  const images = [...(p.image_url ? [p.image_url] : []), ...gallery];
  const year = p.created_at ? String(new Date(p.created_at).getFullYear()) : '2026';
  return {
    id: `p-${p.id}`,
    projectId: p.id,
    code: (p.category || 'PRJ').toUpperCase().slice(0, 12),
    title: p.title,
    artist: p.category || 'Project',
    description: p.description || '',
    format: p.category || 'Project',
    coverColor: '#101317',
    accent: '#E8913C',
    accentColor: '#E8913C',
    image: p.image_url || null,
    images,
    videoUrl: null,
    date: year,
    year,
    count: 0,
    sortOrder: 0,
    githubUrl: p.github_link || null,
    liveUrl: p.demo_link || null,
    stack: p.category ? [p.category] : [],
    isFeatured: !!p.is_featured,
  };
}

function yearOf(d, fallback) {
  if (!d) return fallback;
  const dt = new Date(d);
  return Number.isNaN(dt.getTime()) ? fallback : String(dt.getFullYear());
}

export async function getTimeline() {
  const [releases, certificates, experiences] = await Promise.all([
    getReleases(),
    getCertificates(),
    getExperiences(),
  ]);

  const releaseItems = releases.map((r) => ({
    type: 'project',
    id: r.id,
    ref: r.code,
    title: r.title,
    date: r.date,
    sortDate: r.date ? new Date(r.date.replace(/(\d{2}) (\w{3})/, (_, d, m) => `${d} ${m} ${r.year}`)) : '2026-11-30',
    meta: r.year || '2026',
    link: `/work/${r.id}`,
  }));

  const certItems = certificates.map((c) => ({
    type: 'certificate',
    id: c.id,
    ref: c.year,
    title: c.title,
    date: c.year,
    sortDate: c.createdAt || `${c.year}-12-31`,
    meta: c.issuer,
    link: `/certificate/${c.id}`,
  }));

  // Experience entries (rendered as plain rows, no detail page).
  const expItems = experiences.map((x) => {
    const start = yearOf(x.start_date, '—');
    const end = x.is_current ? 'Present' : yearOf(x.end_date, '');
    return {
      type: 'experience',
      id: x.id,
      ref: x.company,
      title: `${x.role} @ ${x.company}`,
      date: end && end !== start ? `${start} — ${end}` : start,
      sortDate: x.start_date || x.created_at || '2026-01-01',
      meta: x.company,
      link: null,
    };
  });

  return [...releaseItems, ...certItems, ...expItems].sort(
    (a, b) => new Date(a.sortDate) - new Date(b.sortDate)
  );
}

export async function getDates() {
  const releases = await getReleases();
  return releases.map((r) => ({
    code: r.code,
    title: r.title,
    era: `${r.date} ${r.year}`,
    format: r.format,
  }));
}
